let englishDictionaryPromise: Promise<Dictionary> | null = null

function loadEnglishDictionary(): Promise<Dictionary> {
  englishDictionaryPromise ??= import('./i18n.en').then((module) => module.default)
  return englishDictionaryPromise
}

interface I18nContextValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, values?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function format(template: string, values?: Record<string, string | number>): string {
  if (!values) return template
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  )
}

function normalizeLocale(value: string | null): Locale {
  return value === 'en' ? 'en' : 'zh'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('zh')
  const [englishDictionary, setEnglishDictionary] = useState<Dictionary | null>(null)

  const activateEnglish = useCallback(async () => {
    try {
      const dictionary = await loadEnglishDictionary()
      setEnglishDictionary(dictionary)
      setLocaleState('en')
    } catch {
      window.localStorage.setItem(languageStorageKey, 'zh')
    }
  }, [])

  useEffect(() => {
    const legacyLocale = window.localStorage.getItem(legacyLanguageStorageKey)
    const storedLocale = normalizeLocale(window.localStorage.getItem(languageStorageKey) || legacyLocale)
    if (legacyLocale) {
      window.localStorage.setItem(languageStorageKey, storedLocale)
      window.localStorage.removeItem(legacyLanguageStorageKey)
    }
    if (storedLocale === 'zh') return
    const timeout = window.setTimeout(() => void activateEnglish(), 0)
    return () => window.clearTimeout(timeout)
  }, [activateEnglish])

  const setLocale = useCallback((nextLocale: Locale) => {
    window.localStorage.setItem(languageStorageKey, nextLocale)
    if (nextLocale === 'zh') {
      setLocaleState('zh')
      return
    }
    void activateEnglish()
  }, [activateEnglish])

  useEffect(() => {
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
  }, [locale])

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, values) => {
        const dictionary = locale === 'en' && englishDictionary ? englishDictionary : zh
        return format(dictionary[key] ?? key, values)
      },
    }),
    [englishDictionary, locale, setLocale],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error('useI18n must be used within LanguageProvider')
  }
  return context
}
